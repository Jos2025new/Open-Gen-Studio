// Generates src/components/ui/icons.tsx, icon-set-phosphor.ts and icon-set-obra.ts: for each icon the app imports from lucide-react, the Phosphor and Obra
// equivalent (exact name match after normalisation, then ICON_ALIASES). Run: node scripts/gen-icon-map.mjs [--report]
// Adding an icon to the app does not need a rerun: unmapped names fall back to Lucide.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');

/** Lucide name -> [phosphor, obra]: a name, '=' (same name) or null (no equivalent: Lucide stays). Only synonyms the name match cannot find. */
const ICON_ALIASES = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts/icon-aliases.json'), 'utf8'));

const norm = (s) => s.replace(/^Icon(?=[A-Z])/, '').replace(/Icon$/, '').toLowerCase().replace(/[^a-z0-9]/g, '');

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out); else if (/\.(ts|tsx)$/.test(e.name)) out.push(p);
  }
  return out;
}

const names = new Set();
for (const f of walk(path.join(ROOT, 'src'))) {
  if (f.endsWith(path.join('ui', 'icons.tsx'))) continue;
  const src = fs.readFileSync(f, 'utf8');
  for (const m of src.matchAll(/import\s+(type\s+)?\{([^}]*)\}\s+from\s+'(?:lucide-react|\.{1,2}\/(?:[\w.-]+\/)*icons)'/g)) {
    for (const part of m[2].split(',')) {
      const n = part.trim().replace(/^type\s+/, '').split(/\s+as\s+/)[0].trim();
      if (n && n !== 'LucideIcon' && n !== 'LucideProps') names.add(n);
    }
  }
}

const exportsOf = async (pkg) => Object.keys(await import(pkg)).filter((k) => /^[A-Z]/.test(k));
const ph = await exportsOf('@phosphor-icons/react');
const ob = await exportsOf('obra-icons-react');
const index = (list) => { const m = new Map(); for (const k of list) { const n = norm(k); if (!m.has(n) || k.length < m.get(n).length) m.set(n, k); } return m; };
// Phosphor: prefer the "XIcon" export (the bare name is a deprecated alias in 2.x)
const phIdx = index(ph.filter((k) => k.endsWith('Icon') && k !== 'Icon'));
const obIdx = index(ob.filter((k) => k.startsWith('Icon') && k !== 'IconContext'));

// The class lucide puts on each icon (lucide-eye): other sets keep it so selectors and tests keep working.
const React = (await import('react')).default;
const { renderToStaticMarkup } = await import('react-dom/server');
const lucide = await import('lucide-react');

const rows = [];
const miss = { phosphor: [], obra: [] };
for (const n of [...names].sort()) {
  const al = ICON_ALIASES[n] ?? [];
  const pick = (idx, alias, set) => {
    if (alias === null) { miss[set].push(n); return null; }
    const hit = idx.get(norm(alias === undefined || alias === '=' ? n : alias)) ?? null;
    if (!hit) miss[set].push(n);
    return hit;
  };
  const cls = [...new Set(renderToStaticMarkup(React.createElement(lucide[n])).match(/lucide-[a-z0-9-]+/g) ?? [])].join(' ');
  rows.push([n, pick(phIdx, al[0], 'phosphor'), pick(obIdx, al[1], 'obra'), cls]);
}

if (process.argv.includes('--report')) {
  console.log('total', rows.length, 'phosphor', rows.filter((r) => r[1]).length, 'obra', rows.filter((r) => r[2]).length);
  console.log('phosphor missing:', miss.phosphor.join(' '));
  console.log('obra missing:', miss.obra.join(' '));
} else {
  const dir = path.join(ROOT, 'src/components/ui');
  const head = (what) => `// GENERATED by scripts/gen-icon-map.mjs (aliases: scripts/icon-aliases.json). Do not edit by hand.\n// ${what}\n`;
  fs.writeFileSync(path.join(dir, 'icon-set-phosphor.ts'), head('Phosphor equivalent of each icon the app imports, under the Lucide name.') +
    rows.filter((r) => r[1]).map((r) => `export { ${r[1]} as ${r[0]} } from '@phosphor-icons/react';`).join('\n') + '\n');
  fs.writeFileSync(path.join(dir, 'icon-set-obra.ts'), head('Obra equivalent of each icon the app imports, under the Lucide name.') +
    rows.filter((r) => r[2]).map((r) => `export { ${r[2]} as ${r[0]} } from 'obra-icons-react';`).join('\n') + '\n');
  fs.writeFileSync(path.join(dir, 'icons.tsx'), head('Every icon the app uses. Import icons from here, never from lucide-react (icon set: Look → Icons). A name with no Phosphor/Obra equivalent stays Lucide.') +
    `import * as LU from 'lucide-react';
import { makeIcon } from './icon-core';
import * as PH from './icon-set-phosphor';
import * as OB from './icon-set-obra';
export type { IconProps, LucideIcon } from './icon-core';

` + rows.map(([n, p, o, c]) => `export const ${n} = makeIcon('${c}', LU.${n}, ${p ? `PH.${n}` : 'undefined'}, ${o ? `OB.${n}` : 'undefined'});`).join('\n') + '\n');
  console.log('wrote 3 files,', rows.length, 'icons');
}
